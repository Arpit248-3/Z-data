"""SignalGate IBM Architecture Integration — Case Copilot Agent.

Implements the Case Copilot providing evidence-grounded explanatory briefs:
- Accepts exclusively sanitized AgentCaseView instances.
- Rejects any quarantined ground-truth target labels or raw transaction identifiers.
- Operates under strict Action Invariance: agent advice is advisory and can never
  override or alter deterministic routing actions or reason codes.
- Explicitly treats model disagreement as epistemic uncertainty, never proof of fraud.

Governing Specification: docs/ibm_architecture_integration_master_spec.md § C, § J1, § J2
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional, Union
from pydantic import BaseModel, ConfigDict, Field

from integrations.ibm_architecture.agent_view import (
    AgentCaseView,
    check_for_quarantine_violations,
)
from integrations.ibm_architecture.agents.providers import (
    ConfigurableLLMProvider,
    LLMProvider,
    OfflineTemplateProvider,
)
from integrations.ibm_architecture.exceptions import LeakageViolationError


class CopilotBrief(BaseModel):
    """Structured advisory brief generated for an operational fraud triage case."""

    model_config = ConfigDict(extra="forbid", frozen=True)

    case_id: str = Field(description="Sanitized case reference identifier")
    risk_assessment: str = Field(description="Factual assessment of posterior fraud risk")
    uncertainty_interpretation: str = Field(description="Interpretation of ensemble dispersion and uncertainty")
    suggested_investigation_focus: List[str] = Field(
        default_factory=list, description="Recommended checklist items for human analyst"
    )
    mode: Literal["offline_template", "live_llm"] = Field(description="Operational generation mode")
    provider: str = Field(description="Identifier of executing provider implementation")
    is_live_llm: bool = Field(description="Whether output was generated by a live LLM endpoint")
    fallback_reason: Optional[str] = Field(default=None, description="Diagnostic reason if fallback was engaged")
    generated_at: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="Timezone-aware UTC timestamp of brief generation",
    )


class CaseCopilot:
    """Governed Case Copilot generating factual advisory explanations for analysts.

    Authority Boundary:
    The Case Copilot is strictly an advisory aid. It has NO authority to calculate
    fraud scores, set thresholds, or override routing actions.
    """

    def __init__(self, provider: Optional[LLMProvider] = None) -> None:
        self.provider: LLMProvider = provider or OfflineTemplateProvider()

    def explain_case(self, case_view: Union[AgentCaseView, Dict[str, Any]]) -> CopilotBrief:
        """Generate structured CopilotBrief for a sanitized case.

        Raises:
            LeakageViolationError: If quarantined ground-truth or identifier fields are supplied.
            TypeError: If input is neither AgentCaseView nor dictionary.
        """
        # 1. Enforce sanitized view boundary
        if isinstance(case_view, dict):
            check_for_quarantine_violations(case_view, context="CaseCopilot.explain_case")
            view = AgentCaseView(**case_view)
        elif isinstance(case_view, AgentCaseView):
            view = case_view
        else:
            raise TypeError(f"Expected AgentCaseView or dict, got {type(case_view).__name__}")

        # 2. Extract sanitized context
        context: Dict[str, Any] = {
            "record_id": view.record_id,
            "p": view.p,
            "u": view.u,
            "u2": view.u2,
            "n": view.n,
            "action": view.action,
            "reason": view.reason,
            "record_hash": view.record_hash,
            "cfg_hash": view.cfg_hash,
            "split_hash": view.split_hash,
        }

        # 3. Formulate structured prompt
        prompt = (
            f"Analyze fraud triage decision for case {view.record_id}. "
            f"Calibrated probability: {view.p}, Disagreement u2: {view.u2}, "
            f"Routed action: {view.action}, Reason: {view.reason}."
        )

        # 4. Generate brief via provider
        raw_res = self.provider.generate(prompt, context)

        mode_literal: Literal["offline_template", "live_llm"] = (
            "live_llm" if raw_res.get("is_live_llm", False) else "offline_template"
        )

        return CopilotBrief(
            case_id=view.record_id,
            risk_assessment=raw_res.get("risk_assessment", "No assessment available"),
            uncertainty_interpretation=raw_res.get("uncertainty_interpretation", "No uncertainty data"),
            suggested_investigation_focus=raw_res.get("suggested_investigation_focus", []),
            mode=mode_literal,
            provider=raw_res.get("provider", self.provider.provider_name),
            is_live_llm=raw_res.get("is_live_llm", False),
            fallback_reason=raw_res.get("fallback_reason"),
        )
