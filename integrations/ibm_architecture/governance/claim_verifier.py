"""SignalGate IBM Architecture Integration — Deterministic Claim Verification Engine.

Enforces that LLM agents cannot display unverified statements or arbitrary prose.
All statements presented to fraud analysts must be generated by a registered template
populated exclusively by verified facts cross-checked against the permitted AgentCaseView.

Key Invariants:
1. Extra or malformed claim fields are rejected.
2. Only explicitly registered (field, operator) pairs are permitted.
3. Values are verified strictly against the permitted AgentCaseView.
4. Only registered template_id values are permitted.
5. Final prose is rendered strictly from reviewed templates after verification.
6. The verifier is completely deterministic.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from typing import Any, List, Mapping, Optional, Set, Tuple

from integrations.ibm_architecture.agent_view import AgentCaseView
from integrations.ibm_architecture.contracts import Action, Claim, ReasonCode


# Registered template definitions for verified claim presentation
REGISTERED_TEMPLATES: dict[str, str] = {
    "T1_CALIBRATED_RISK": "Case {record_id} evaluated with calibrated fraud risk p={p:.4f}.",
    "T2_MODEL_DISAGREEMENT": "Ensemble disagreement across members is u={u:.4f}.",
    "T3_ROUTING_ACTION": "Deterministic triage assigned action '{action}' with reason code '{reason}'.",
    "T4_HIGH_RISK_THRESHOLD": "Calibrated risk p={p:.4f} is at or above review threshold {threshold:.4f}.",
    "T5_MODERATE_RISK_RANGE": "Calibrated risk p={p:.4f} falls within intermediate review band [{lower:.4f}, {upper:.4f}].",
    "T6_ELEVATED_DISAGREEMENT": "Disagreement signal u={u:.4f} is elevated above baseline spread {threshold:.4f}.",
    "T7_ROBUST_MAD_SIGNAL": "Robust disagreement MAD from median is u2={u2:.4f}.",
    "T8_RECORD_PROVENANCE": "Audit provenance verified against config hash {cfg_hash_short} and split hash {split_hash_short}.",
    "T9_MEMBER_COUNT": "Ensemble evaluated with n={n:.0f} active scoring members.",
}

# Explicitly allowed (field, operator) combinations
ALLOWED_FIELD_OPERATORS: Set[Tuple[str, str]] = {
    ("p", "eq"),
    ("p", "lt"),
    ("p", "lte"),
    ("p", "gt"),
    ("p", "gte"),
    ("u", "eq"),
    ("u", "lt"),
    ("u", "lte"),
    ("u", "gt"),
    ("u", "gte"),
    ("u2", "eq"),
    ("u2", "lt"),
    ("u2", "lte"),
    ("u2", "gt"),
    ("u2", "gte"),
    ("n", "eq"),
    ("n", "gte"),
    ("action", "eq"),
    ("action", "in"),
    ("reason", "eq"),
    ("reason", "in"),
    ("record_id", "eq"),
    ("cfg_hash", "eq"),
    ("split_hash", "eq"),
    ("record_hash", "eq"),
}


@dataclass(frozen=True)
class VerificationResult:
    """Outcome of verifying a single structured claim against an AgentCaseView."""

    is_verified: bool
    statement: Optional[str]
    rejection_reason: Optional[str]


class ClaimVerifier:
    """Deterministic, schema-enforcing claim verifier."""

    def __init__(
        self,
        templates: Optional[Mapping[str, str]] = None,
        allowed_field_operators: Optional[Set[Tuple[str, str]]] = None,
        tolerance: float = 1e-4,
    ) -> None:
        self.templates = dict(templates or REGISTERED_TEMPLATES)
        self.allowed_field_operators = set(allowed_field_operators or ALLOWED_FIELD_OPERATORS)
        self.tolerance = tolerance

    def verify(self, claim: Claim, case_view: AgentCaseView) -> VerificationResult:
        """Verify a single claim against an AgentCaseView."""
        # 1. Validate template registration
        if claim.template_id not in self.templates:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Unregistered template_id: '{claim.template_id}'",
            )

        # 2. Validate field and operator registration
        key = (claim.field, claim.operator)
        if key not in self.allowed_field_operators:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Disallowed field-operator pair: ({claim.field}, {claim.operator})",
            )

        # 3. Retrieve actual value from case_view
        if not hasattr(case_view, claim.field):
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Field '{claim.field}' not found in AgentCaseView",
            )

        actual_val = getattr(case_view, claim.field)
        if actual_val is None:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Field '{claim.field}' is None in AgentCaseView",
            )

        # Unpack enum instances to strings if needed
        if hasattr(actual_val, "value"):
            actual_val = actual_val.value
        claim_val = claim.value.value if hasattr(claim.value, "value") else claim.value

        # 4. Evaluate comparison operator
        is_valid = self._evaluate_operator(actual_val, claim.operator, claim_val)
        if not is_valid:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=(
                    f"Factual check failed for field '{claim.field}': "
                    f"actual={actual_val} does not satisfy {claim.operator} {claim.value}"
                ),
            )

        # 5. Render statement from approved template
        try:
            rendered = self._render_template(claim.template_id, claim, case_view)
            return VerificationResult(
                is_verified=True,
                statement=rendered,
                rejection_reason=None,
            )
        except Exception as e:
            return VerificationResult(
                is_verified=False,
                statement=None,
                rejection_reason=f"Template rendering failed: {str(e)}",
            )

    def _evaluate_operator(self, actual: Any, operator: str, expected: Any) -> bool:
        """Deterministically evaluate comparison operator with floating point tolerance."""
        if operator == "eq":
            if isinstance(actual, (int, float)) and isinstance(expected, (int, float)):
                return math.isclose(float(actual), float(expected), abs_tol=self.tolerance)
            return str(actual) == str(expected)

        if operator == "ne":
            if isinstance(actual, (int, float)) and isinstance(expected, (int, float)):
                return not math.isclose(float(actual), float(expected), abs_tol=self.tolerance)
            return str(actual) != str(expected)

        if operator == "lt":
            return float(actual) < float(expected)

        if operator == "lte":
            return float(actual) <= float(expected) or math.isclose(
                float(actual), float(expected), abs_tol=self.tolerance
            )

        if operator == "gt":
            return float(actual) > float(expected)

        if operator == "gte":
            return float(actual) >= float(expected) or math.isclose(
                float(actual), float(expected), abs_tol=self.tolerance
            )

        if operator == "in":
            if isinstance(expected, (list, tuple, set)):
                return actual in expected or str(actual) in [str(x) for x in expected]
            return False

        return False

    def _render_template(self, template_id: str, claim: Claim, case_view: AgentCaseView) -> str:
        """Format the registered template strictly from verified facts."""
        template_str = self.templates[template_id]
        context: dict[str, Any] = {
            "record_id": case_view.record_id,
            "p": case_view.p or 0.0,
            "u": case_view.u or 0.0,
            "u2": case_view.u2 or 0.0,
            "n": case_view.n or 0.0,
            "action": case_view.action.value if hasattr(case_view.action, "value") else str(case_view.action),
            "reason": case_view.reason.value if hasattr(case_view.reason, "value") else str(case_view.reason),
            "cfg_hash_short": case_view.cfg_hash[:8],
            "split_hash_short": case_view.split_hash[:8],
        }

        # Add claim values for threshold / band templates
        if isinstance(claim.value, (int, float)):
            context["threshold"] = float(claim.value)
        elif isinstance(claim.value, (list, tuple)) and len(claim.value) == 2:
            context["lower"] = float(claim.value[0])
            context["upper"] = float(claim.value[1])

        return template_str.format(**context)
